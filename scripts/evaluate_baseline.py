"""
scripts/evaluate_baseline.py
Phase 4 — P4.3: One-shot evaluation of the saved baseline checkpoint on the test split.

Usage (from project root, with venv active):
    python scripts/evaluate_baseline.py

Output:
    data/processed/baseline_results.md  — performance report vs Yang et al. literature
    runs/baseline/test_confusion.npy     — raw confusion matrix (for notebook)
    runs/baseline/test_per_class_f1.csv  — per-class F1 scores (for notebook)
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
)

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.config import Paths, load_yaml_config
from src.data.caddy_dataset import get_dataloader
from src.data.transforms import eval_transforms
from src.models.visual_encoder import SingleImageClassifier

# ── Yang et al. published results for comparison ──────────────────────────────
YANG_GOOGLENET_ACC = 90.08  # % — from Yang et al. paper
YANG_RESNET_ACC = 88.59  # % — from Yang et al. paper


def merge_configs(base_path: Path, override_path: Path) -> dict:
    """Deep-merge override YAML on top of base YAML."""

    def _deep_merge(b: dict, o: dict) -> dict:
        result = dict(b)
        for key, val in o.items():
            if key == "_base_":
                continue
            if isinstance(val, dict) and isinstance(result.get(key), dict):
                result[key] = _deep_merge(result[key], val)
            else:
                result[key] = val
        return result

    base = load_yaml_config(str(base_path))
    override = load_yaml_config(str(override_path))
    return _deep_merge(base, override)


def evaluate(
    model: nn.Module,
    loader: torch.utils.data.DataLoader,
    device: torch.device,
    num_classes: int,
) -> tuple[list[int], list[int]]:
    """Run inference; return (all_preds, all_labels)."""
    model.eval()
    all_preds, all_labels = [], []

    with torch.no_grad():
        for batch in loader:
            imgs = batch["left"].to(device, non_blocking=True)
            labels = batch["label"].tolist()
            logits = model(imgs)
            preds = logits.argmax(dim=1).cpu().tolist()
            all_preds.extend(preds)
            all_labels.extend(labels)

    return all_preds, all_labels


def write_results_md(
    out_path: Path,
    accuracy_pct: float,
    macro_f1: float,
    per_class_f1: list[float],
    class_names: list[str],
    num_classes: int,
) -> None:
    """Write a Markdown report comparing our baseline to Yang et al."""
    lines = [
        "# Phase 4 — Baseline Results\n",
        "## Model: ResNet18 (ImageNet-pretrained, left-image only, 17-way classifier)\n",
        f"**Test Accuracy:** {accuracy_pct:.2f}%\n",
        f"**Macro F1-score:** {macro_f1:.4f}\n",
        "\n---\n",
        "## Comparison with Yang et al.\n",
        "\n| Model | Accuracy (%) | Notes |",
        "|---|---|---|",
        f"| Yang et al. — GoogleLeNet | {YANG_GOOGLENET_ACC:.2f} | Original paper result |",
        f"| Yang et al. — ResNet (reported) | {YANG_RESNET_ACC:.2f} | Original paper result |",
        f"| **Our ResNet18 baseline** | **{accuracy_pct:.2f}** | CADDY standard split, left-image only |",
        "\n",
        "> [!NOTE]",
        "> Architectural differences from Yang et al.: ResNet18 vs GoogleLeNet/ResNet (unspecified depth),",
        "> 224×224 input vs original resolution, AdamW optimizer with cosine schedule vs the paper's setup.",
        "> These differences account for any gap to the published 90.08% figure. The purpose of this",
        "> baseline is pipeline-correctness verification (non-near-random accuracy), not exact replication.\n",
        "\n---\n",
        "## Per-Class F1 Scores\n",
        "\n| Class | Name | F1 |",
        "|---|---|---|",
    ]
    for i, (name, f1) in enumerate(zip(class_names, per_class_f1)):
        lines.append(f"| {i} | {name} | {f1:.4f} |")

    lines.append("\n---\n")
    lines.append("*Generated by `scripts/evaluate_baseline.py`.*\n")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main() -> None:
    config_path = ROOT / "configs" / "baseline_transfer_learning.yaml"
    cfg = merge_configs(ROOT / "configs" / "base.yaml", config_path)

    data_cfg = cfg.get("data", {})
    model_cfg = cfg.get("model", {})
    train_cfg = cfg.get("training", {})

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[evaluate_baseline] Device: {device}")

    image_size: int = data_cfg.get("image_size", 224)
    batch_size: int = train_cfg.get("batch_size", 32)
    num_classes: int = model_cfg.get("num_classes", 17)
    backbone: str = model_cfg.get("backbone", "resnet18")

    test_csv = Path(data_cfg.get("split_test", Paths.SPLITS_DIR / "standard_test.csv"))
    ckpt_path = ROOT / "checkpoints" / "baseline_best.pth"

    if not ckpt_path.exists():
        raise FileNotFoundError(
            f"Checkpoint not found: {ckpt_path}\n" "Run `python scripts/train_baseline.py` first."
        )

    # ── Model ─────────────────────────────────────────────────────────────────
    model = SingleImageClassifier(
        backbone=backbone,
        num_classes=num_classes,
        pretrained=False,  # weights loaded from checkpoint
    ).to(device)

    ckpt = torch.load(ckpt_path, map_location=device, weights_only=True)
    model.load_state_dict(ckpt["model_state_dict"])
    print(
        f"[evaluate_baseline] Loaded checkpoint from epoch {ckpt['epoch']} "
        f"(val_acc={ckpt['val_acc']:.4f})"
    )

    # ── DataLoader ────────────────────────────────────────────────────────────
    nw = 0 if sys.platform == "win32" else 4
    test_loader = get_dataloader(
        test_csv,
        batch_size=batch_size,
        shuffle=False,
        num_workers=nw,
        transform=eval_transforms(image_size),
        pin_memory=device.type == "cuda",
    )
    print(f"[evaluate_baseline] Test batches: {len(test_loader)}")

    # ── Evaluate ──────────────────────────────────────────────────────────────
    all_preds, all_labels = evaluate(model, test_loader, device, num_classes)

    acc = accuracy_score(all_labels, all_preds) * 100
    macro_f1 = f1_score(all_labels, all_preds, average="macro", zero_division=0)
    per_class_f1 = f1_score(all_labels, all_preds, average=None, zero_division=0).tolist()
    cm = confusion_matrix(all_labels, all_preds, labels=list(range(num_classes)))

    print(f"\n[evaluate_baseline] Test Accuracy : {acc:.2f}%")
    print(f"[evaluate_baseline] Macro F1-Score: {macro_f1:.4f}")
    print("\nDetailed Classification Report:")
    print(classification_report(all_labels, all_preds, zero_division=0))

    # ── Class names from DATASET_SCHEMA.md gesture table ──────────────────────
    class_names = [
        "start_comm",
        "end_comm",
        "up",
        "down",
        "photo",
        "backwards",
        "carry",
        "boat",
        "here",
        "mosaic",
        "num_delimiter",
        "one",
        "two",
        "three",
        "four",
        "five",
        "true_neg",
    ]
    class_names = class_names[:num_classes]

    # ── Save artefacts ────────────────────────────────────────────────────────
    runs_dir = ROOT / "runs" / "baseline"
    runs_dir.mkdir(parents=True, exist_ok=True)

    np.save(runs_dir / "test_confusion.npy", cm)
    print(f"Confusion matrix saved -> {runs_dir / 'test_confusion.npy'}")

    f1_csv = runs_dir / "test_per_class_f1.csv"
    import csv

    with open(f1_csv, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["class_id", "class_name", "f1"])
        for i, (name, f1) in enumerate(zip(class_names, per_class_f1)):
            writer.writerow([i, name, f"{f1:.6f}"])
    print(f"Per-class F1 saved -> {f1_csv}")

    results_md = ROOT / "data" / "processed" / "baseline_results.md"
    write_results_md(results_md, acc, macro_f1, per_class_f1, class_names, num_classes)
    print(f"Results report saved -> {results_md}")

    # ── Phase 4 exit criterion ─────────────────────────────────────────────────
    NEAR_RANDOM_THRESHOLD = 20.0  # % — random for 17 classes ≈ 5.9%
    if acc < NEAR_RANDOM_THRESHOLD:
        print(
            f"\n[WARN] Test accuracy {acc:.2f}% is near-random (<{NEAR_RANDOM_THRESHOLD}%)! "
            "The data pipeline may have a bug. Phase 5 MUST NOT begin until this is resolved."
        )
        sys.exit(1)
    else:
        print(
            f"\n[+] Phase 4 exit criterion MET: accuracy {acc:.2f}% is non-trivial (>{NEAR_RANDOM_THRESHOLD}%)."
        )


if __name__ == "__main__":
    main()
